import release from '../package.json' with {type:'json'}
import {pauseAtStart} from './playback-helpers'
import {test,expect,type Page} from '@playwright/test'
const add=async(page:Page,q:string)=>{await page.getByRole('combobox',{name:'Search flights'}).fill(q);await page.getByRole('combobox',{name:'Search flights'}).press('Enter')}

test('renderer switches preserve clock, carrier and airport; GPU draws and falls back after context loss',async({page})=>{
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message))
 await page.goto('./');await pauseAtStart(page)
 await add(page,'SWISS')
 await expect(page.locator('.selection-summary')).toContainText('97 aircraft')
 await add(page,'ZRH');await page.getByRole('button',{name:'ZRH board'}).click()
 await expect(page.locator('.count')).toHaveText(/^[1-9]\d* aircraft.*SWISS/)
 const count=await page.locator('.count').innerText()
 await page.getByRole('button',{name:'Close airport board'}).click()
 await page.getByRole('button',{name:'View settings',exact:true}).click()
 const renderer=page.getByRole('combobox',{name:'Aircraft renderer'})
 await renderer.selectOption('three');await expect(renderer).toHaveValue('three');await expect(renderer).toBeEnabled()
 await expect(page.locator('.gpu-layer')).toHaveCount(1)
 await expect(page.getByRole('slider')).toHaveValue('25200')
 await expect(page.locator('.count')).toHaveText(count)
 await expect(page.getByRole('button',{name:'ZRH board'})).toBeVisible()
 await page.getByRole('button',{name:'Device details'}).click()
 await expect(page.locator('.diagnostics')).toContainText('Three.js')
 await expect(page.locator('.diagnostics')).toContainText(/[1-9]\d* GPU draw calls/)
 await page.evaluate(()=>Object.defineProperty(navigator,'clipboard',{value:{writeText:async(text:string)=>{(window as any).__copiedResults=text}},configurable:true}))
 await page.getByRole('button',{name:'Copy results'}).click();await expect(page.locator('.diagnostics')).toContainText('Results copied')
 const copied=await page.evaluate(()=>JSON.parse((window as any).__copiedResults));expect(copied.renderer).toBe('three');expect(copied.release).toBe(release.version);expect(copied.gpu.calls).toBeGreaterThan(0);expect(copied.stagesP95Ms).toEqual(expect.objectContaining({sampling:expect.any(Number),geometry:expect.any(Number),submission:expect.any(Number)}));expect(copied.gpu.stateUploadBytes).toBeGreaterThan(0)
 await page.screenshot({path:`test-results/${test.info().project.name}-three.png`,fullPage:true})
 await page.getByRole('button',{name:'Reset measurements'}).click()
 await page.getByRole('button',{name:'Device details'}).click()
 await page.getByRole('combobox',{name:'Playback speed'}).selectOption('900')
 await page.getByRole('button',{name:'Play',exact:true}).click()
 await expect.poll(async()=>Number(await page.getByRole('slider').inputValue())).toBeGreaterThan(26400)
 await page.getByRole('button',{name:'Pause',exact:true}).click()
 await renderer.selectOption('canvas');await expect(page.locator('.gpu-layer')).toHaveCount(0)
 const time=await page.getByRole('slider').inputValue()
 await renderer.selectOption('three');await expect(page.locator('.gpu-layer')).toHaveCount(1);await expect(page.getByRole('slider')).toHaveValue(time)
 await page.locator('.gpu-layer').evaluate((canvas:HTMLCanvasElement)=>canvas.getContext('webgl2')!.getExtension('WEBGL_lose_context')!.loseContext())
 await expect(renderer).toHaveValue('canvas');await expect(page.locator('.gpu-layer')).toHaveCount(0)
 await expect(page.locator('.renderer-picker')).toContainText('context lost')
 await expect(page.getByRole('slider')).toHaveValue(time)
 expect(errors).toEqual([])
})
