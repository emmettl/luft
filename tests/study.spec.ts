import {test,expect,type Page} from '@playwright/test'
const add=async(page:Page,query:string,name:RegExp)=>{const search=page.getByRole('combobox',{name:'Search flights'});await search.fill(query);await page.getByRole('option',{name}).click()}
const ready=async(page:Page)=>{await page.goto('./');await expect(page.locator('.play')).toBeEnabled()}

test('unified pills combine airlines, airports and routes across map, activity and boards',async({page})=>{
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message))
 await ready(page)
 const allActivity=await page.locator('.ms-study-timeline svg').innerHTML()
 await add(page,'swiss',/^SWISS/)
 await expect(page.locator('.selection-summary')).toContainText('97 aircraft')
 await expect(page.locator('.count')).toContainText('SWISS')
 expect(await page.locator('.ms-study-timeline svg').innerHTML()).not.toEqual(allActivity)
 await add(page,'easyjet',/^easyJet/)
 await expect(page.getByRole('group',{name:'Selected filters'})).toContainText('SWISS')
 await expect(page.getByRole('group',{name:'Selected filters'})).toContainText('easyJet')
 await expect(page.locator('.selection-summary')).toContainText('458 aircraft')
 await add(page,'ZRH',/^ZRH Zurich/)
 await expect(page.locator('.ms-airport-hero')).toHaveCount(0)
 await expect(page.locator('.airport-key')).toContainText('inbound')
 await page.getByRole('button',{name:'ZRH board'}).click()
 await expect(page.locator('.ms-airport-hero')).toContainText('ZRH')
 await expect(page.locator('.ms-split-flap-board__select').first()).toBeVisible()
 await page.locator('.ms-split-flap-board__select').first().click()
 await expect(page.locator('.flight-caption')).toBeVisible()
 await page.getByRole('button',{name:'Close airport board'}).click()
 await add(page,'LHR',/^LHR London/)
 await expect(page.getByRole('button',{name:'LHR board'})).toBeVisible()
 await page.getByRole('button',{name:'Remove easyJet'}).click()
 await add(page,'LHR ZRH',/^LHR ↔ ZRH/)
 await expect(page.locator('.ms-study-timeline__heading')).toContainText('LHR ↔ ZRH')
 await expect(page.locator('.selection-summary')).not.toContainText('0 aircraft')
 await page.getByRole('button',{name:'View settings',exact:true}).click()
 await page.getByRole('button',{name:'Hour density',exact:true}).click()
 await expect(page.locator('.count')).toContainText('5-minute snapshots')
 await page.getByRole('button',{name:'Motion',exact:true}).click()
 await page.getByRole('button',{name:'Close view settings'}).click()
 await page.screenshot({path:`test-results/${test.info().project.name}-multi-selection.png`,fullPage:true})
 await page.getByRole('button',{name:'Clear all',exact:true}).click()
 await expect(page.getByRole('group',{name:'Selected filters'})).toHaveCount(0)
 expect(await page.locator('.ms-study-timeline svg').innerHTML()).toEqual(allActivity)
 expect(errors).toEqual([])
})

